# Paths for data
DATA_PATH = '/content/drive/MyDrive/Data/'
HYPERSPECTRAL_FILE = DATA_PATH + 'Indian_pines_corrected.mat'
LABEL_FILE = DATA_PATH + 'Indian_pines_gt.mat'

# Load data
data = sio.loadmat(HYPERSPECTRAL_FILE)['indian_pines_corrected']
labels = sio.loadmat(LABEL_FILE)['indian_pines_gt']

# PCA for Dimensionality Reduction
def apply_pca(X, num_components=30):
    newX = np.reshape(X, (-1, X.shape[2]))  # Flatten spatial dimensions
    pca = PCA(n_components=num_components, whiten=True)
    newX = pca.fit_transform(newX)
    return np.reshape(newX, (X.shape[0], X.shape[1], num_components)), pca

# Apply PCA
data_pca, pca = apply_pca(data, num_components=30)

# Create Patches for Training
def create_patches(X, y, patch_size):
    margin = patch_size // 2
    padded_X = np.pad(X, ((margin, margin), (margin, margin), (0, 0)), mode='constant')
    patches = []
    labels = []
    for i in range(margin, padded_X.shape[0] - margin):
        for j in range(margin, padded_X.shape[1] - margin):
            patch = padded_X[i-margin:i+margin+1, j-margin:j+margin+1, :]
            patches.append(patch)
            labels.append(y[i-margin, j-margin])
    return np.array(patches), np.array(labels)

PATCH_SIZE = 15
patches, patch_labels = create_patches(data_pca, labels, PATCH_SIZE)

# Filter non-zero labels
non_zero_indices = patch_labels > 0
patches = patches[non_zero_indices]
patch_labels = patch_labels[non_zero_indices] - 1

# Train-test split
X_train, X_test, y_train, y_test = train_test_split(patches, patch_labels, test_size=0.3, random_state=42)

# Define a Deep 2D CNN Model
def build_2d_cnn(input_shape, num_classes):
    model = models.Sequential([
        layers.Conv2D(64, (3, 3), activation='relu', padding='same', input_shape=input_shape),
        layers.Conv2D(64, (3, 3), activation='relu', padding='same'),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(0.3),

        layers.Conv2D(128, (3, 3), activation='relu', padding='same'),
        layers.Conv2D(128, (3, 3), activation='relu', padding='same'),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(0.3),

        layers.Conv2D(256, (3, 3), activation='relu', padding='same'),
        layers.Conv2D(256, (3, 3), activation='relu', padding='same'),
        layers.MaxPooling2D((2, 2)),
        layers.Dropout(0.3),

        layers.Conv2D(512, (3, 3), activation='relu', padding='same'),
        layers.Conv2D(512, (3, 3), activation='relu', padding='same'),
        layers.GlobalAveragePooling2D(),

        layers.Dense(512, activation='relu'),
        layers.Dropout(0.5),
        layers.Dense(num_classes, activation='softmax')
    ])
    return model

# Build Model
input_shape = (PATCH_SIZE, PATCH_SIZE, data_pca.shape[-1])
num_classes = np.unique(patch_labels).shape[0]
model = build_2d_cnn(input_shape, num_classes)
model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

# Train Model
history = model.fit(
    X_train, y_train,
    validation_data=(X_test, y_test),
    epochs=20,  # Adjust as needed
    batch_size=64
)

# Improved Visualization with Ground Truth, Full Prediction, and Masked Prediction
def visualize_results(data_pca, labels, model, patch_size):
    margin = patch_size // 2
    padded_data = np.pad(data_pca, ((margin, margin), (margin, margin), (0, 0)), mode='constant')

    patches = []
    for i in range(margin, padded_data.shape[0] - margin):
        for j in range(margin, padded_data.shape[1] - margin):
            patch = padded_data[i-margin:i+margin+1, j-margin:j+margin+1, :]
            patches.append(patch)
    patches = np.array(patches)

    predictions = model.predict(patches, batch_size=64, verbose=1)
    predicted_labels = np.argmax(predictions, axis=-1).reshape(labels.shape)

    # Masked Prediction: Only display predictions where labels are non-zero
    predicted_labels_masked = predicted_labels * (labels != 0)

    plt.figure(figsize=(15, 5))

    plt.subplot(1, 3, 1)
    plt.title("Ground Truth")
    plt.imshow(labels, cmap='jet')

    plt.subplot(1, 3, 2)
    plt.title("Predicted (Full)")
    plt.imshow(predicted_labels, cmap='jet')

    plt.subplot(1, 3, 3)
    plt.title("Predicted (Masked)")
    plt.imshow(predicted_labels_masked, cmap='jet')

    plt.show()

# Run visualization
visualize_results(data_pca, labels, model, PATCH_SIZE)